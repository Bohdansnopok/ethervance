export function translateText(value: string): string {
  const normalized = value.replace(/\s+/g, " ").trim();
  const exact = translations[normalized];
  if (exact) return exact;
  const networkStatus = normalized.match(/^Выбрана сеть (\d+)\. Для действий Qairos нужна Ethereum Mainnet\.$/);
  if (networkStatus) return `Network ${networkStatus[1]} selected. Qairos actions require Ethereum Mainnet.`;
  const txSent = normalized.match(/^Транзакция отправлена: (.+) Ожидаем подтверждение блока\.$/);
  if (txSent) return `Transaction sent: ${txSent[1]} Waiting for block confirmation.`;
  const txFailed = normalized.match(/^Транзакция отменена или завершилась ошибкой: (.+)$/);
  if (txFailed) return `Transaction was cancelled or failed: ${txFailed[1]}`;
  const confirmed = normalized.match(/^Подтверждено в блоке (\d+)\. Хэш: (.+)$/);
  if (confirmed) return `Confirmed in block ${confirmed[1]}. Hash: ${confirmed[2]}`;
  const httpError = normalized.match(/^Сервис Mainnet вернул HTTP (\d+)\.$/);
  if (httpError) return `Mainnet service returned HTTP ${httpError[1]}.`;
  const entropy = normalized.match(/^Ключ ML-DSA-44 создан локально\. Источник энтропии: (.+)\. Секретная часть останется в памяти этой вкладки\.$/);
  if (entropy) return `ML-DSA-44 key generated locally. Entropy source: ${translateText(entropy[1])}. The secret key will stay in this tab's memory.`;
  const position = normalized.match(/^Позиция (ДА|НЕТ) · рынок (\d+)$/);
  if (position) return `${position[1] === "ДА" ? "YES" : "NO"} position · market ${position[2]}`;
  const networkChip = normalized.match(/^СЕТЬ (\d+)$/);
  if (networkChip) return `NETWORK ${networkChip[1]}`;
  const sessionExpiry = normalized.match(/^Выполнен вход · до (.+)$/);
  if (sessionExpiry) return `Signed in · expires ${sessionExpiry[1]}`;
  const walletRequest = normalized.match(/^Ожидаем подтверждение в (.+)…$/);
  if (walletRequest) return `Waiting for approval in ${walletRequest[1]}…`;
  return value;
}

function localizeNode(node: ReactNode): ReactNode {
  if (typeof node === "string") return translateText(node);
  if (Array.isArray(node)) return node.map(localizeNode);
  if (!isValidElement<{ children?: ReactNode }>(node)) return node;

  const props = { ...node.props } as Record<string, unknown>;
  for (const attribute of ["aria-label", "title", "placeholder", "alt"]) {
    const value = props[attribute];
    if (typeof value === "string") props[attribute] = translateText(value);
  }
  if ("children" in props)
    props.children = localizeNode(props.children as ReactNode);
  return cloneElement(node, props);
}

export function EnglishContent({ children }: { children: ReactNode }) {
  return <>{Children.map(children, localizeNode)}</>;
}
